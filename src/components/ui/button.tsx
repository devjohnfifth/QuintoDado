/**
 * Classes do botão já passadas pelo `cn` (tailwind-merge). Sem isso, um link
 * estilizado como botão receberia `rounded-lg` da base e `rounded-full` da
 * variante ao mesmo tempo, e quem vence depende da ordem do CSS gerado.
 */
function buttonVariants(props?: Parameters<typeof buttonVariantsBase>[0]) {
  return cn(buttonVariantsBase(props))
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariantsBase>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={buttonVariants({ variant, size, className })}
      {...props}
    />
  )
}

export { Button, buttonVariants }
